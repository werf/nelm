func TestLoad_TSNodeModules(t *testing.T) {
	contexts := map[string]context.Context{
		"vanilla": context.Background(),
		"werf": nelmcommon.ContextWithHelmOptions(context.Background(), nelmcommon.HelmOptions{
			ChartLoadOpts: nelmcommon.ChartLoadOptions{ChartType: nelmcommon.LegacyChartTypeChart, NoSecrets: true},
		}),
	}

	for _, apiVersion := range []string{"v2", "v3"} {
		for ctxName, ctx := range contexts {
			t.Run(apiVersion+"/"+ctxName+"/directory", func(t *testing.T) {
				dir := filepath.Join(t.TempDir(), "mychart")
				writeTestFile(t, filepath.Join(dir, "Chart.yaml"), "apiVersion: "+apiVersion+"\nname: mychart\nversion: 1.0.0\n")
				writeTestFile(t, filepath.Join(dir, "ts", "src", "index.ts"), "export {};\n")
				writeTestFile(t, filepath.Join(dir, "ts", "node_modules", "dep", "index.js"), "module.exports = {};\n")
				writeTestFile(t, filepath.Join(dir, "charts", "sub", "Chart.yaml"), "apiVersion: v2\nname: sub\nversion: 1.0.0\n")
				writeTestFile(t, filepath.Join(dir, "charts", "sub", "ts", "src", "index.ts"), "export {};\n")
				writeTestFile(t, filepath.Join(dir, "charts", "sub", "ts", "node_modules", "dep", "index.js"), "module.exports = {};\n")

				// Native binaries, such as the one of esbuild, are larger than a chart file may be.
				for _, chartDir := range []string{dir, filepath.Join(dir, "charts", "sub")} {
					bigFile := filepath.Join(chartDir, "ts", "node_modules", "esbuild", "bin", "esbuild")
					writeTestFile(t, bigFile, "")
					require.NoError(t, os.Truncate(bigFile, archive.MaxDecompressedFileSize+1))
				}

				loaded, err := LoadDir(ctx, dir)
				require.NoError(t, err)
				assertNoTSNodeModules(t, loaded)
			})

			t.Run(apiVersion+"/"+ctxName+"/archive", func(t *testing.T) {
				loaded, err := LoadArchive(ctx, bytes.NewReader(tarGzTestChart(t, map[string]string{
					"mychart/Chart.yaml":                               "apiVersion: " + apiVersion + "\nname: mychart\nversion: 1.0.0\n",
					"mychart/ts/src/index.ts":                          "export {};\n",
					"mychart/ts/node_modules/dep/index.js":             "module.exports = {};\n",
					"mychart/charts/sub/Chart.yaml":                    "apiVersion: v2\nname: sub\nversion: 1.0.0\n",
					"mychart/charts/sub/ts/node_modules/dep/index.js": "module.exports = {};\n",
					"mychart/charts/sub/ts/node_modules/dep/dep.prov":  "provenance\n",
					"mychart/ts/node_modules/esbuild/bin/esbuild":      strings.Repeat("\x00", int(archive.MaxDecompressedFileSize)+1),
				})))
				require.NoError(t, err)
				assertNoTSNodeModules(t, loaded)
			})
		}
	}
}

func assertNoTSNodeModules(t *testing.T, loaded helmchart.Charter) {
	t.Helper()

	accessor, err := helmchart.NewAccessor(loaded)
	require.NoError(t, err)

	names := append(testFileNames(accessor.Files()), testFileNames(accessor.RuntimeFiles())...)
	assert.Contains(t, names, "ts/src/index.ts")

	for _, name := range names {
		assert.NotContains(t, name, "node_modules")
	}

	require.Len(t, accessor.Dependencies(), 1)

	dep, err := helmchart.NewAccessor(accessor.Dependencies()[0])
	require.NoError(t, err)

	for _, name := range append(testFileNames(dep.Files()), testFileNames(dep.RuntimeFiles())...) {
		assert.NotContains(t, name, "node_modules")
	}
}

func tarGzTestChart(t *testing.T, files map[string]string) []byte {
	t.Helper()

	var buf bytes.Buffer

	gzWriter := gzip.NewWriter(&buf)
	tarWriter := tar.NewWriter(gzWriter)

	for name, content := range files {
		require.NoError(t, tarWriter.WriteHeader(&tar.Header{Name: name, Mode: 0o644, Size: int64(len(content)), Typeflag: tar.TypeReg}))

		_, err := tarWriter.Write([]byte(content))
		require.NoError(t, err)
	}

	require.NoError(t, tarWriter.Close())
	require.NoError(t, gzWriter.Close())

	return buf.Bytes()
}
