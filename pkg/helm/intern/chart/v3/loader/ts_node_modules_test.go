package loader

import (
	"context"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/werf/nelm/v2/pkg/helm/pkg/chart/loader/archive"
)

func TestLoadFilesSkipsTSNodeModules(t *testing.T) {
	loaded, err := LoadFiles(context.Background(), []*archive.BufferedFile{
		{Name: "Chart.yaml", Data: []byte("apiVersion: v3\nname: mychart\nversion: 1.0.0\n")},
		{Name: "ts/node_modules/dep/index.js", Data: []byte("module.exports = {};\n")},
		{Name: "charts/sub/Chart.yaml", Data: []byte("apiVersion: v2\nname: sub\nversion: 1.0.0\n")},
		{Name: "charts/sub/ts/node_modules/dep/dep.prov", Data: []byte("provenance\n")},
	})
	require.NoError(t, err)

	for _, file := range loaded.Files {
		assert.NotContains(t, file.Name, "node_modules")
	}

	require.Len(t, loaded.Dependencies(), 1)

	for _, file := range loaded.Dependencies()[0].Files {
		assert.NotContains(t, file.Name, "node_modules")
	}
}
